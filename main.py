@app.post("/whatsapp")
async def whatsapp_webhook(Body: str = Form(default="")):
    twiml = MessagingResponse()
    
    try:
        user_message = Body.strip() if Body else ""
        if not user_message:
            bot_reply = "שלום! הגעת להנדי פלוס. במה נוכל לעזור היום?"
        elif not client:
            bot_reply = "שלום! הגעת להנדי פלוס. ליצירת קשר וקבלת שירות: 055-9821845."
        else:
            response = client.models.generate_content(
                model='gemini-3.6-flash',
                contents=user_message,
                config={'system_instruction': SYSTEM_PROMPT}
            )
            bot_reply = response.text.strip() if response and response.text else "תודה על פנייתך! נציג יחזור אליך בהקדם."
            
    except Exception as e:
        print("=== ERROR IN WHATSAPP WEBHOOK ===")
        traceback.print_exc()
        bot_reply = "תודה שפנית להנדי פלוס! לקבלת מענה מהיר ניתן ליצור קשר במספר: 055-9821845."

    twiml.message(bot_reply)
    return Response(content=str(twiml), media_type="application/xml")
